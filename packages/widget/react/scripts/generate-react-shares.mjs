import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import configOf, { WIDGET_EXPOSES } from '../../../../apps/widget-cdn/rspack.config.mjs';

const require = createRequire(new URL('../../../../apps/widget-cdn/package.json', import.meta.url));
const { rspack } = require('@rspack/core');
const requests = new Set(['react', 'react-dom']);

// Follow the actual browser graph, including lazy and emitted JSX imports.
// Analyze both modes without emitting assets or running federation.
const compiler = rspack(['production', 'development'].map((mode) => {
  const config = configOf({}, { mode });
  return {
    ...config,
    mode,
    devtool: false,
    entry: Object.fromEntries(Object.entries(WIDGET_EXPOSES).map(([name, path]) => [name.slice(2), path])),
    output: { ...config.output, clean: false },
    optimization: { minimize: false },
    plugins: [
      ...config.plugins.filter((plugin) => plugin.constructor.name === 'ProvidePlugin'),
      { apply(compiler) {
        compiler.hooks.shouldEmit.tap('ReactShares', () => false);
        compiler.hooks.normalModuleFactory.tap('ReactShares', (factory) => {
          factory.hooks.beforeResolve.tap('ReactShares', (data) => {
            if (data && /^(react|react-dom)(\/|$)/.test(data.request)) requests.add(data.request);
          });
        });
      } },
    ],
  };
}));
try {
  const stats = await new Promise((resolve, reject) => compiler.run((error, result) => error ? reject(error) : resolve(result)));
  if (stats.hasErrors()) throw new Error(stats.toString({ all: false, errors: true }));
} finally {
  await new Promise((resolve, reject) => compiler.close((error) => error ? reject(error) : resolve()));
}

const modules = [...requests].sort();
const source = `// Generated by scripts/generate-react-shares.mjs. Do not edit.
import type { SharedLib } from '@layerswap/widget-js';

export async function loadHostReactShares(reactVersion: string, reactDOMVersion: string): Promise<Record<string, SharedLib>> {
  reactVersion = reactVersion.split('-')[0];
  reactDOMVersion = reactDOMVersion.split('-')[0];
  if (reactVersion !== reactDOMVersion || !/^(18|19)\\./.test(reactVersion)) {
    throw new Error('[layerswap/widget-react] React and ReactDOM must have the same supported version (18 or 19).');
  }
  const namespaces = await Promise.all([
${modules.map((name) => `    import(${JSON.stringify(name)}),`).join('\n')}
  ]);
  const modules = namespaces.map((namespace) => ('default' in namespace ? namespace.default : namespace));
  return {
${modules.map((name, index) => `    ${JSON.stringify(name)}: { version: ${name.startsWith('react-dom') ? 'reactDOMVersion' : 'reactVersion'}, lib: () => modules[${index}], requiredVersion: ">=18.0.0 <20.0.0" },`).join('\n')}
  };
}
`;
const target = new URL('../src/reactShares.generated.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== source) throw new Error('[react-sharing] Providers are stale. Run generate:shares after building packages, rebuild the loader, and release it with the CDN.');
} else {
  writeFileSync(target, source);
}
console.log(`[react-sharing] ${modules.length} host modules discovered.`);
